"""Builds SaveKey's translation files from the tables in this folder.

Each strings_*.py file calls K(english, de=..., es=..., fr=..., it=..., br=..., pt=...). The English text is
the key, exactly as written in the Swift code (interpolations become %@ for text and %lld for numbers).
`br` is Portuguese (Brazil); `pt` is Portuguese (Portugal) and defaults to `br` when it is the same.
Use positional placeholders (%1$@, %2$lld) when a translation has more than one.

Writes Shared/Localization/<language>.lproj/Localizable.strings and InfoPlist.strings, used by the app
and the AutoFill extension. Run after editing a table:  python3 Tools/Localization/make_strings.py
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "Shared" / "Localization"
LANGS = ["de", "es", "fr", "it", "pt-BR", "pt-PT"]

STRINGS: dict[str, dict[str, str]] = {}
INFO_PLIST: dict[str, dict[str, str]] = {}


def _entry(key, de, es, fr, it, br, pt):
    return {"en": key, "de": de, "es": es, "fr": fr, "it": it, "pt-BR": br, "pt-PT": br if pt is None else pt}


def K(key, de, es, fr, it, br, pt=None):
    if key in STRINGS:
        sys.exit(f"duplicate key: {key!r}")
    STRINGS[key] = _entry(key, de, es, fr, it, br, pt)


def INFO(plist_key, english, de, es, fr, it, br, pt=None):
    INFO_PLIST[plist_key] = _entry(english, de, es, fr, it, br, pt)


def load():
    for table in sorted(HERE.glob("strings_*.py")):
        exec(compile(table.read_text(), str(table), "exec"), {"K": K, "INFO": INFO})


PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(@|lld|d|%)")


def placeholders(text):
    """Types of the placeholders in order of argument position (positional ones sorted by number)."""
    found, plain = [], 0
    for m in PLACEHOLDER.finditer(text):
        if m.group(2) == "%":
            continue
        if m.group(1):
            found.append((int(m.group(1)), m.group(2)))
        else:
            plain += 1
            found.append((plain, m.group(2)))
    return sorted(found)


def check():
    problems = []
    for key, values in STRINGS.items():
        want = placeholders(key)
        for lang, value in values.items():
            if placeholders(value) != want:
                problems.append(f"{lang}: placeholders differ for {key!r}: {value!r}")
            if not value.strip() and key.strip():
                problems.append(f"{lang}: empty translation for {key!r}")
    return problems


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write():
    for lang in ["en"] + LANGS:
        folder = OUT / f"{lang}.lproj"
        folder.mkdir(parents=True, exist_ok=True)
        lines = ["/* SaveKey — generated by Tools/Localization/make_strings.py. Edit the tables there. */", ""]
        for key in sorted(STRINGS, key=str.lower):
            lines.append(f"{quote(key)} = {quote(STRINGS[key][lang])};")
        (folder / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        info = ["/* SaveKey — generated by Tools/Localization/make_strings.py. */", ""]
        for plist_key, values in INFO_PLIST.items():
            info.append(f"{plist_key} = {quote(values[lang])};")
        (folder / "InfoPlist.strings").write_text("\n".join(info) + "\n", encoding="utf-8")


if __name__ == "__main__":
    load()
    issues = check()
    if issues:
        print("\n".join(issues))
        sys.exit(1)
    write()
    print(f"{len(STRINGS)} strings and {len(INFO_PLIST)} Info.plist strings written for en + {', '.join(LANGS)}")
